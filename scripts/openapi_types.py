"""Small, strict OpenAPI-to-TypeScript renderer for GridWatch's actual JSON contracts."""

import json
import re
from typing import cast


def mapping(value: object) -> dict[str, object]:
    if not isinstance(value, dict):
        raise ValueError("Expected an OpenAPI object")
    return cast(dict[str, object], value)


def sequence(value: object) -> list[object]:
    if not isinstance(value, list):
        raise ValueError("Expected an OpenAPI array")
    return cast(list[object], value)


def identifier(value: str) -> str:
    if not re.fullmatch(r"[A-Za-z_$][A-Za-z0-9_$]*", value):
        raise ValueError(f"Unsupported TypeScript identifier: {value}")
    return value


def render_type(value: object) -> str:
    if value is True:
        return "unknown"
    if value is False:
        return "never"
    schema = mapping(value)
    if "$ref" in schema:
        reference = str(schema["$ref"])
        prefix = "#/components/schemas/"
        if not reference.startswith(prefix):
            raise ValueError(f"Unsupported schema reference: {reference}")
        return identifier(reference.removeprefix(prefix))
    if "const" in schema:
        return json.dumps(schema["const"])
    if "enum" in schema:
        return " | ".join(json.dumps(item) for item in sequence(schema["enum"]))
    for key, separator in (("anyOf", " | "), ("oneOf", " | "), ("allOf", " & ")):
        if key in schema:
            return separator.join(f"({render_type(item)})" for item in sequence(schema[key]))
    kind = schema.get("type")
    if kind == "string" and schema.get("format") == "binary":
        return "Blob"
    if kind in ("number", "integer"):
        return "number"
    if kind in ("string", "boolean", "null"):
        return str(kind)
    if kind == "array":
        if "prefixItems" in schema:
            return (
                "[" + ", ".join(render_type(item) for item in sequence(schema["prefixItems"])) + "]"
            )
        return f"Array<{render_type(schema.get('items', {}))}>"
    if kind == "object" or "properties" in schema:
        properties = mapping(schema.get("properties", {}))
        required = sequence(schema.get("required", []))
        fields = [
            f"{json.dumps(name)}{'' if name in required else '?'}: {render_type(prop)};"
            for name, prop in properties.items()
        ]
        extra = schema.get("additionalProperties", True)
        if not fields:
            return f"Record<string, {render_type(extra)}>"
        result = "{ " + " ".join(fields) + " }"
        if isinstance(extra, dict):
            result += f" & Record<string, {render_type(extra)}>"
        return result
    if kind is None and set(schema) <= {"title", "description", "default", "examples"}:
        return "unknown"
    raise ValueError(f"Unsupported OpenAPI schema: {schema}")


def generate_types(document: dict[str, object]) -> str:
    schemas = mapping(mapping(document["components"])["schemas"])
    lines = ["// Generated by make types from OpenAPI. Do not edit.", ""]
    for name in sorted(schemas):
        lines.append(f"export type {identifier(name)} = {render_type(schemas[name])};")
    lines.extend(["", "export interface ApiOperations {"])
    for path, item in sorted(mapping(document["paths"]).items()):
        for method, operation_value in mapping(item).items():
            if method not in {"get", "post", "put", "patch", "delete"}:
                continue
            operation = mapping(operation_value)
            params: dict[str, list[str]] = {"path": [], "query": []}
            for value in sequence(operation.get("parameters", [])):
                parameter = mapping(value)
                location = str(parameter["in"])
                if location not in params:
                    raise ValueError(f"Unsupported parameter location: {location}")
                name = json.dumps(parameter["name"])
                optional = "" if parameter.get("required") else "?"
                params[location].append(f"{name}{optional}: {render_type(parameter['schema'])};")
            responses = mapping(operation["responses"])
            success = [value for status, value in responses.items() if status.startswith("2")]
            if len(success) != 1:
                raise ValueError("Each operation must define one successful JSON response")
            content = mapping(mapping(success[0])["content"])
            media = "application/json" if "application/json" in content else "text/csv"
            response_schema = mapping(content[media])["schema"]
            request_body = "never"
            if "requestBody" in operation:
                request_content = mapping(mapping(operation["requestBody"])["content"])
                request_media = (
                    "application/json"
                    if "application/json" in request_content
                    else "multipart/form-data"
                )
                request_body = render_type(mapping(request_content[request_media])["schema"])
            lines.extend(
                [
                    f"  {json.dumps(method.upper() + ' ' + path)}: {{",
                    "    path: "
                    + (
                        "{ " + " ".join(params["path"]) + " }"
                        if params["path"]
                        else "Record<string, never>"
                    )
                    + ";",
                    "    query: "
                    + (
                        "{ " + " ".join(params["query"]) + " }"
                        if params["query"]
                        else "Record<string, never>"
                    )
                    + ";",
                    f"    response: {render_type(response_schema)};",
                    f"    body: {request_body};",
                    "  };",
                ]
            )
    lines.append("}")
    return "\n".join(lines) + "\n"
