"""Export the M0 health contract from OpenAPI; extend for new schemas in M3/M4."""

import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "backend"))

from app.main import app  # noqa: E402


def main() -> None:
    """Generate the health interface from its actual schema, without hand-copied API types."""
    schema = app.openapi()["components"]["schemas"]["HealthResponse"]
    fields = []
    for name, prop in schema["properties"].items():
        if "const" not in prop:
            raise ValueError(f"Unsupported M0 property: {name}")
        fields.append(f"  {name}: {json.dumps(prop['const'])};")
    output = "// Generated by make types from OpenAPI. Do not edit.\n"
    output += "export interface HealthResponse {\n" + "\n".join(fields) + "\n}\n"
    (ROOT / "frontend/src/api/generated.ts").write_text(output, encoding="utf-8")
    print("Generated frontend/src/api/generated.ts")


if __name__ == "__main__":
    main()
